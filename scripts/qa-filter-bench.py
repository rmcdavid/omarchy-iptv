#!/usr/bin/env python3
"""qa-filter-bench.py -- time Model.filterChannels in the QML JS engine.

Standard library only. Nothing is written inside the repo; everything lands in
--work (default: a fresh mkdtemp) and nothing touches the network: the playlist
is generated by scripts/gen-playlist.py and parsed by bin/omarchy-iptv.

WHY THIS SCRIPT EXISTS, and why it builds its channels the long way round.

F-PERF-1 was measured twice on a fixture written BY HAND in the bench itself:
ten thousand objects carrying name, group, url, searchKey and nameKey. The
helper writes four more fields, and one of them decided the measurement.
`Model.channelId` returns `channel.id` when the channel has one and otherwise
hashes the URL with fnv1a32, and `filterChannels` calls it once per MATCHING
row to order favourites first. `assign_ids` has run on every parse since the
first commit, so every cache this plugin has ever written carries `id` on every
channel -- and the hand-built fixture carried it on none. The filter therefore
hashed 6,877 URLs per keystroke that the shipped code never hashes.

Measured on the real 10,000-channel cache, 50 iterations, Qt 6.11.2:

    query   as the helper writes it   with id/tvgId stripped
    a             26.52 ms                  95.28 ms
    e             27.22 ms                  91.28 ms
    s             26.42 ms                  87.76 ms
    t             25.82 ms                  79.38 ms
    news          13.24 ms                  22.00 ms
    sky sports    10.56 ms                  10.44 ms

3.6x, and it was the whole of the residual: the board carried "64 ms on a
single character, over the 30 ms budget" and proposed not filtering until the
second keystroke to remove it. On the bytes the helper actually writes there is
no over-budget case to remove, and that UX change would have cost a real
feature to fix a defect that existed only in a test fixture.

CLAUDE.md rule 10 says a double must never be more FORGIVING than the real
thing. This one was HARSHER, which is the failure mode the rule does not name
and which is worse for a measurement: a forgiving double hides a defect, a
harsh one INVENTS one, and an invented defect gets paid for in product. So this
bench does not describe the helper's output, it runs the helper -- and it
refuses to measure a channel list missing any field the helper emits.
"""
import argparse, json, os, shutil, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# What bin/omarchy-iptv writes onto a parsed channel. ALWAYS is unconditional
# -- the four fields of the record template plus the two derived keys; OPTIONAL
# is written only where the playlist carries the attribute. The authority is
# the helper, not this list: tests/test_helper.py imports both tuples and
# checks them against a real parse, so a field added to the parser turns the
# gate red rather than quietly making the next bench unfaithful.
ALWAYS_FIELDS = ("id", "name", "group", "url", "searchKey", "nameKey")
OPTIONAL_FIELDS = ("chno", "groups", "headers", "logo", "tvgId", "tvgName")

QUERIES = ("a", "e", "s", "t", "news", "sky sports")

QML = '''import QtQuick
import QtTest
import "Model.js" as M
import "Channels.js" as C

TestCase {
  name: "FilterBench"

  function bench(channels, q, iters) {
    for (var w = 0; w < 10; w++) M.filterChannels(channels, q, 200)
    var t0 = Date.now()
    var r = null
    for (var i = 0; i < iters; i++) r = M.filterChannels(channels, q, 200)
    return { ms: (Date.now() - t0) / iters, total: r.total }
  }

  function test_filter_cost() {
    compare(C.CHANNELS.length, %(count)d)
    console.info("QML ENGINE, %(count)d channels from the helper, %(iters)d iterations, %(budget)d ms budget")
    console.info("  query            ms      over budget   matches")
    var qs = %(queries)s
    for (var i = 0; i < qs.length; i++) {
      var r = bench(C.CHANNELS, qs[i], %(iters)d)
      var pad = "               ".substring(0, Math.max(1, 15 - qs[i].length))
      console.info("  " + qs[i] + pad + r.ms.toFixed(2) + " ms   "
                   + (r.ms > %(budget)d ? "OVER      " : "ok        ") + "    " + r.total)
    }
  }
}
'''


def run(argv, **kw):
    out = subprocess.run(argv, capture_output=True, text=True, **kw)
    if out.returncode != 0:
        sys.stderr.write(out.stdout + out.stderr)
        raise SystemExit("failed: %s" % argv[0])
    return out


def channels_from_helper(work, count, groups, seed):
    """Generate a playlist and parse it with the shipping helper."""
    m3u = os.path.join(work, "gen.m3u")
    run([sys.executable, os.path.join(ROOT, "scripts", "gen-playlist.py"),
         "--channels", str(count), "--groups", str(groups), "--seed", str(seed),
         "--epg-ids", "0.6", "--out", m3u])
    cache = os.path.join(work, "cache")
    os.makedirs(cache, exist_ok=True)
    run([os.path.join(ROOT, "bin", "omarchy-iptv"), "playlist",
         "--url", m3u, "--cache-dir", cache])
    for root, _dirs, files in os.walk(cache):
        if "channels.json" in files:
            with open(os.path.join(root, "channels.json")) as fh:
                data = json.load(fh)
            return data["channels"] if isinstance(data, dict) else data
    raise SystemExit("the helper wrote no channels.json under %s" % cache)


def unfaithful(channels):
    """What makes this channel list something the helper would not have produced.

    Returns a list of complaints, empty when the list is faithful. Shared with
    tests/test_helper.py so the bench's refusal and the gate's assertion are
    one function rather than two descriptions of one rule.
    """
    if not channels:
        return ["no channels at all"]
    out = []
    for field in ALWAYS_FIELDS:
        absent = sum(1 for c in channels if field not in c)
        if absent:
            out.append("%s missing from %d of %d rows; the helper writes it on every one"
                       % (field, absent, len(channels)))
    known = set(ALWAYS_FIELDS) | set(OPTIONAL_FIELDS)
    seen = set()
    for c in channels:
        seen.update(c.keys())
    for extra in sorted(seen - known):
        out.append("%s is on the channels and in neither ALWAYS_FIELDS nor OPTIONAL_FIELDS; "
                   "the parser grew a field this bench does not know about" % extra)
    return out


def verify_faithful(channels):
    """Refuse to measure a fixture the helper would not have produced."""
    complaints = unfaithful(channels)
    if complaints:
        raise SystemExit("UNFAITHFUL FIXTURE, refusing to measure:\n  - "
                         + "\n  - ".join(complaints)
                         + "\nThis is the F-PERF-1 mistake; see the module docstring.")
    print("fixture: %d channels, every unconditional helper field present on every row"
          % len(channels))


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--channels", type=int, default=10000)
    ap.add_argument("--groups", type=int, default=120)
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--iterations", type=int, default=50)
    ap.add_argument("--budget", type=int, default=30, help="keystroke budget in ms")
    ap.add_argument("--work", default=None, help="scratch directory (default: mkdtemp, removed after)")
    ap.add_argument("--strip", action="append", default=[], metavar="FIELD",
                    help="delete FIELD from every channel before measuring; the bench then "
                         "reports what an unfaithful fixture would have said instead of refusing")
    args = ap.parse_args()

    work = args.work or tempfile.mkdtemp(prefix="qa-filter-bench-")
    os.makedirs(work, exist_ok=True)
    made_temp = args.work is None
    try:
        channels = channels_from_helper(work, args.channels, args.groups, args.seed)
        if args.strip:
            for c in channels:
                for field in args.strip:
                    c.pop(field, None)
            print("STRIPPED %s -- this is NOT what the helper writes; the numbers below "
                  "measure a fixture, not the product." % ", ".join(args.strip))
        else:
            verify_faithful(channels)

        bench = os.path.join(work, "bench")
        os.makedirs(bench, exist_ok=True)
        os.symlink(os.path.join(ROOT, "Model.js"), os.path.join(bench, "Model.js"))
        with open(os.path.join(bench, "Channels.js"), "w") as fh:
            fh.write(".pragma library\nvar CHANNELS = ")
            json.dump(channels, fh, separators=(",", ":"))
            fh.write("\n")
        with open(os.path.join(bench, "tst_filter.qml"), "w") as fh:
            fh.write(QML % {"count": len(channels), "iters": args.iterations,
                            "budget": args.budget, "queries": json.dumps(list(QUERIES))})

        env = dict(os.environ, QT_QPA_PLATFORM="offscreen")
        out = subprocess.run(["/usr/lib/qt6/bin/qmltestrunner", "-input", "tst_filter.qml"],
                             cwd=bench, env=env, capture_output=True, text=True)
        for line in (out.stdout + out.stderr).splitlines():
            if "qml:" in line:
                print(line.split("qml:", 1)[1].rstrip())
            elif line.startswith("FAIL"):
                print(line)
        return out.returncode
    finally:
        if made_temp:
            shutil.rmtree(work, ignore_errors=True)


if __name__ == "__main__":
    raise SystemExit(main())
